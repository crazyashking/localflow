"""End-to-end ASR check against known reference text.

Uses WAVs generated by Windows SAPI so the expected transcription is known
exactly. This exercises the real Transcriber, not a mock, and reports word
error rate plus decode speed.

Run:  .venv\\Scripts\\python.exe bench\\test_pipeline.py
"""

from __future__ import annotations

import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from faster_whisper.audio import decode_audio  # noqa: E402

from localflow import asr  # noqa: E402

SAMPLES = Path(__file__).parent / "samples"


_UNITS = {
    "zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6,
    "seven": 7, "eight": 8, "nine": 9, "ten": 10, "eleven": 11, "twelve": 12,
    "thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16,
    "seventeen": 17, "eighteen": 18, "nineteen": 19,
}
_TENS = {
    "twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60,
    "seventy": 70, "eighty": 80, "ninety": 90,
}
_SCALES = {"hundred": 100, "thousand": 1000, "million": 1000000}
_NUMBER_WORDS = set(_UNITS) | set(_TENS) | set(_SCALES)


def _collapse_numbers(tokens: list[str]) -> list[str]:
    """Turn number words into digits so "four hundred" == "400".

    Whisper normalises spoken numbers to numerals. Scoring that as an error
    would make the harness lie about accuracy, and every tuning decision made
    against it would be wrong.
    """
    out: list[str] = []
    i = 0
    while i < len(tokens):
        if tokens[i] not in _NUMBER_WORDS:
            out.append(tokens[i])
            i += 1
            continue

        total = 0
        current = 0
        consumed = 0
        while i + consumed < len(tokens):
            word = tokens[i + consumed]
            if word in _UNITS:
                current += _UNITS[word]
            elif word in _TENS:
                current += _TENS[word]
            elif word == "hundred":
                current = max(current, 1) * 100
            elif word in ("thousand", "million"):
                total += max(current, 1) * _SCALES[word]
                current = 0
            elif word == "and" and consumed > 0:
                # "four hundred and twenty" reads as one number
                nxt = tokens[i + consumed + 1] if i + consumed + 1 < len(tokens) else ""
                if nxt not in _NUMBER_WORDS:
                    break
            else:
                break
            consumed += 1

        out.append(str(total + current))
        i += consumed
    return out


def normalise(text: str) -> list[str]:
    """Lowercase, strip punctuation, canonicalise numbers, for fair WER."""
    text = text.lower()
    text = re.sub(r"[^a-z0-9\s]", " ", text)
    return _collapse_numbers(text.split())


def wer(reference: str, hypothesis: str) -> float:
    """Levenshtein distance over words, divided by reference length."""
    ref, hyp = normalise(reference), normalise(hypothesis)
    if not ref:
        return 0.0 if not hyp else 1.0

    prev = list(range(len(hyp) + 1))
    for i, r in enumerate(ref, 1):
        cur = [i] + [0] * len(hyp)
        for j, h in enumerate(hyp, 1):
            cur[j] = min(
                prev[j] + 1,          # deletion
                cur[j - 1] + 1,       # insertion
                prev[j - 1] + (r != h),  # substitution
            )
        prev = cur
    return prev[-1] / len(ref)


def load_references() -> dict[str, str]:
    refs: dict[str, str] = {}
    ref_file = SAMPLES / "reference.txt"
    for line in ref_file.read_text(encoding="utf-8-sig").splitlines():
        if "=>" in line:
            key, value = line.split("=>", 1)
            refs[key.strip()] = value.strip()
    return refs


def main() -> int:
    refs = load_references()
    if not refs:
        print("no reference sentences found")
        return 1

    print("loading model ...")
    t0 = time.perf_counter()
    transcriber = asr.Transcriber()
    transcriber.load()
    print(f"warm in {time.perf_counter() - t0:.1f}s (this is paid once at startup)\n")

    total_wer = 0.0
    total_audio = 0.0
    total_decode = 0.0
    failures = 0

    for key in sorted(refs):
        wav = SAMPLES / f"{key}.wav"
        if not wav.exists():
            print(f"{key}: missing {wav.name}")
            failures += 1
            continue

        clip = decode_audio(str(wav), sampling_rate=16000)
        result = transcriber.transcribe(clip)
        score = wer(refs[key], result.text)

        total_wer += score
        total_audio += result.audio_seconds
        total_decode += result.decode_seconds

        status = "ok" if score <= 0.10 else "HIGH WER"
        print(f"[{key}] {status}  wer={score:.1%}  {result.audio_seconds:.1f}s audio  "
              f"{result.decode_seconds:.2f}s decode ({result.speed:.0f}x)")
        print(f"      ref: {refs[key]}")
        print(f"      got: {result.text}\n")
        if score > 0.10:
            failures += 1

    n = len(refs)
    print("-" * 66)
    print(f"mean WER      {total_wer / n:.1%}")
    print(f"total audio   {total_audio:.1f}s")
    print(f"total decode  {total_decode:.2f}s  ({total_audio / total_decode:.0f}x real time)")
    print(f"result        {n - failures}/{n} within 10% WER")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
